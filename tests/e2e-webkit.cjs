const assert=require('node:assert/strict');const {webkit,devices}=require('playwright');
(async()=>{const browser=await webkit.launch();const page=await browser.newPage({...devices['iPhone 13'],locale:'pt-BR'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const res=await page.goto('https://khassiooluver1988-droid.github.io/VIRA-APP/',{waitUntil:'domcontentloaded',timeout:60000});
assert.equal(res.status(),200);await page.getByText('Entre para a comunidade KORA').waitFor({timeout:30000});
assert.equal(await page.locator('.auth-panel').count(),1);
await page.locator('[data-act="mode"][data-id="signup"]').click();
assert.equal(await page.locator('input[name="email"]').count(),1);
assert.deepEqual(errors,[]);
console.log('PASSOU: URL principal da KORA no navegador WebKit iPhone, login e cadastro disponíveis.');
await browser.close();})().catch(e=>{console.error(e);process.exitCode=1});
