const assert = require('node:assert/strict');
const { webkit, devices } = require('playwright');

(async () => {
  const browser = await webkit.launch({headless:true});
  const errors=[];
  const page = await browser.newPage({...devices['iPhone 13'], locale:'pt-BR'});
  page.on('pageerror',error=>errors.push(error.message));
  const url='https://khassiooluver1988-droid.github.io/VIRA-APP/';
  const response=await page.goto(url,{waitUntil:'domcontentloaded',timeout:60000});
  assert.equal(response.status(),200,'Site público não respondeu HTTP 200');
  await page.locator('#view .post').first().waitFor();
  assert.equal(await page.locator('.bottom-nav .nav-link').count(),5);
  await page.locator('.bottom-nav [data-route="explorar"]').click();
  await page.locator('#view h1').filter({hasText:'Explorar'}).waitFor();
  await page.locator('.person [data-act="follow"]').first().click();
  assert.match(await page.locator('.person [data-act="follow"]').first().innerText(),/Seguindo/);
  await page.locator('.bottom-nav [data-route="inicio"]').click();
  await page.locator('.post .heart').first().click();
  assert.equal(await page.locator('.post .heart.liked').count(),1);
  await page.locator('.composer [data-act="create-post"]').first().click();
  await page.locator('#post-caption').fill('Teste público do VIRA, sem publicar dados reais.');
  await page.locator('#post-form button[type="submit"]').click();
  await page.getByText('Teste público do VIRA, sem publicar dados reais.').first().waitFor();
  await page.locator('.bottom-nav [data-route="resolver"]').click();
  await page.locator('[data-act="create-request"]').first().click();
  await page.locator('#req-title').fill('Preciso de uma dica útil');
  await page.locator('#req-desc').fill('Quero testar a publicação de um pedido na versão online.');
  await page.locator('#request-form button[type="submit"]').click();
  await page.locator('#view').getByText('Preciso de uma dica útil').waitFor();
  await page.locator('[data-act="request-answers"]').first().click();
  await page.locator('#answer-input').fill('Resposta local de teste');
  await page.locator('#answer-form button[type="submit"]').click();
  await page.getByText('Resposta local de teste').waitFor();
  await page.locator('[data-act="close-dialog"]').click();
  await page.locator('[data-act="request-resolve"]').first().click();
  await page.locator('#view .status.done').waitFor();
  await page.locator('.topbar [data-act="messages"]').click();
  await page.locator('[data-act="messages-with"]').first().click();
  await page.locator('#msg-input').fill('Mensagem local de teste');
  await page.locator('#message-form button[type="submit"]').click();
  await page.locator('.bubble').filter({hasText:'Mensagem local de teste'}).waitFor();
  await page.locator('[data-act="close-dialog"]').click();
  await page.locator('.bottom-nav [data-route="perfil"]').click();
  await page.locator('[data-act="edit-profile"]').click();
  await page.locator('#profile-name').fill('Usuário Safari');
  await page.locator('#profile-form button[type="submit"]').click();
  await page.getByText('Usuário Safari').first().waitFor();
  assert.deepEqual(errors,[],'Falhas de JavaScript no navegador WebKit');
  console.log('PASSOU — navegador WebKit com viewport de iPhone; HTTP 200; navegar, seguir, curtir, publicar, pedir, responder, resolver, mensagens e editar perfil.');
  await browser.close();
})().catch(error=>{console.error(error);process.exitCode=1;});
