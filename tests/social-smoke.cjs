const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM} = require('jsdom');

const html = fs.readFileSync('docs/index.html','utf8');
const script = fs.readFileSync('docs/social.js','utf8');
const dom = new JSDOM(html,{url:'https://example.org/VIRA-APP/',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,d=w.document;
w.scrollTo=()=>{};
w.confirm=()=>true;
w.alert=(msg)=>{throw new Error('alert inesperado: '+msg)};
const errors=[];
w.addEventListener('error',e=>errors.push(e.message));
w.eval(script);

const pause=()=>new Promise(r=>setTimeout(r,30));
const find=sel=>{const x=d.querySelector(sel);assert.ok(x,'elemento não localizado: '+sel);return x};
const click=sel=>{find(sel).click()};
const field=(sel,value)=>{const e=find(sel);e.value=value;e.dispatchEvent(new w.Event('input',{bubbles:true}))};
const submit=sel=>find(sel).dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));

(async()=>{
 assert.match(find('#view').textContent,/Momentos/);
 assert.equal(d.querySelectorAll('#bottom-nav .nav-link').length,5);
 click('[data-route="explorar"]');
 assert.match(find('#view').textContent,/Explorar/);
 click('.person [data-act="follow"]');
 assert.match(find('.person [data-act="follow"]').textContent,/Seguindo/);
 click('[data-route="inicio"]');
 click('.post [data-act="like"]');
 assert.ok(d.querySelector('.post .heart.liked'),'curtida não atualizou');
 click('.post [data-act="comments"]');
 field('#comment-input','Comentário de teste');
 submit('#comment-form');await pause();
 assert.match(find('#comment-list').textContent,/Comentário de teste/);
 click('[data-act="close-dialog"]');
 click('.composer button[data-act="create-post"]');
 field('#post-caption','Olá VIRA, meu primeiro post de teste!');
 submit('#post-form');await pause();
 assert.match(find('#view').textContent,/Olá VIRA/);
 click('[data-route="resolver"]');
 click('[data-act="create-request"]');
 field('#req-title','Preciso de orientação');
 field('#req-desc','Quero dicas para começar um negócio local e divulgar serviços.');
 submit('#request-form');await pause();
 assert.match(find('#view').textContent,/Preciso de orientação/);
 click('[data-act="request-answers"]');
 field('#answer-input','Exemplo de resposta útil');
 submit('#answer-form');await pause();
 assert.match(find('.dialog').textContent,/Exemplo de resposta útil/);
 click('[data-act="close-dialog"]');
 click('[data-act="request-resolve"]');
 assert.match(find('#view').textContent,/Resolvido/);
 click('[data-act="messages"]');
 click('[data-act="messages-with"]');
 field('#msg-input','Olá, mensagem simulada');
 submit('#message-form');await pause();
 assert.match(find('.dialog').textContent,/Olá, mensagem simulada/);
 click('[data-act="close-dialog"]');
 click('[data-route="perfil"]');
 click('[data-act="edit-profile"]');
 field('#profile-name','Pessoa VIRA');
 submit('#profile-form');await pause();
 assert.match(find('#view').textContent,/Pessoa VIRA/);
 click('[data-act="settings"]');
 click('[data-act="clear-all"]');
 assert.match(find('#view').textContent,/Momentos/);
 assert.equal(JSON.parse(w.localStorage.getItem('vira_social_demo_v2')).requests.length,0);
 assert.deepEqual(errors,[],'Erros JS de execução');
 console.log('PASSOU: 15 cenários (5 abas, seguir, curtir, comentar, publicar, pedidos, responder, resolver, mensagens, perfil, limpar e persistência).');
 dom.window.close();
})().catch(e=>{console.error(e);process.exitCode=1});
